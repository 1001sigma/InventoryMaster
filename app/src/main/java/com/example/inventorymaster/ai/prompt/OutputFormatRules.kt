package com.example.inventorymaster.ai.prompt

/**
 * 输出格式规则库（docs/AI_UI_OPTIMIZATION.md「输出格式规范」）：
 * 全局输出形态的集中约束 = 意图→格式三形态映射 + 反向约束（防格式泛滥）。
 *
 * 职责边界（v3 各司其职设计不变）：本库只管**全局排版风格**；
 * 工具相关的呈现规则仍在各工具 description / 返回 content 内
 * （如 QueryRecordsTool 的"勿逐条罗列"、ExecuteUiActionTool 的动作→参数对照）。
 * PromptBuilder 组装系统提示词时调用 [render]。
 *
 * 相对外部通用模板的适配：
 * - LaTeX 一节反转为**禁用**（mikepenz 渲染器不支持公式，输出 $$ 会原样裸露）；
 * - 表格的适用条件明确包含"多字段库存明细"（本 App 查询结果的主形态，
 *   端侧由 AutoWrapMarkdownTable 保证渲染质量）；
 * - 补充分隔线（---）约束：聊天流里分隔线易与消息边界混淆。
 */
object OutputFormatRules {

    fun render(): String = """
        ## 输出格式规范（按意图自适应，只选一种排版形态）
        1. **纯自然文本**（闲聊寒暄、简短问答、翻译、单步计算、开放式建议）：
           直接给结论、保持对话感；严禁使用标题（#/##）、表格、列表与分隔线。
        2. **结构化富文本**（多步骤方案、分析报告、多角度长答）：
           用 ## 分段（最多 2~4 个）；步骤用编号列表（1. 2. 3.），属性归纳用短横列表（-）；
           仅对关键结论/参数名行内加粗，严禁整段大面积加粗。
        3. **特殊结构**（多字段数据、多维度对比、代码）：
           表格仅用于 2 个以上字段的记录并列（如库存明细/效期对比）——单维度清单严禁做成表格；
           代码必须用三个反引号+语言名包裹，不得混入正文。
        ## 反向约束（防格式泛滥）
        - 200 字以内的短回答或单一主题，严禁使用 ## 标题；
        - 数字/百分比/温度/单位等保持纯文本，严禁 LaTeX 或公式语法（本应用不渲染公式）；
        - 非代码内容不得套用代码块；不要用分隔线（---）装饰排版；
        - 格式服务于信息：拿不准时选更低一档的排版形态。
    """.trimIndent()
}
